module.exports = {
  inputs: {
    record: {
      type: 'ref',
      required: true,
    },
    values: {
      type: 'ref',
      required: true,
    },
    actorUser: {
      type: 'ref',
      required: true,
    },
    request: {
      type: 'ref',
    },
  },

  async fn(inputs) {
    const { values } = inputs;

    const team = await Team.qm.updateOne(inputs.record.id, values);

    if (team) {
      sails.sockets.broadcast('user', 'teamUpdate', {
        item: team,
      });
    }

    return team;
  },
};
